"""Generate wavelink/nr_bg1.py from Sionna's 5G_bg1.csv and cross-check it against AFF3CT's lifted matrices.

    python3 tools/gen_nr_bg1.py <sionna>/src/sionna/phy/fec/ldpc/codes/5G_bg1.csv <aff3ct-conf>/dec/LDPC/5G wavelink/nr_bg1.py

Sionna: https://github.com/NVlabs/sionna   AFF3CT: https://github.com/aff3ct/configuration_files
"""
import sys, os, glob, re
csv, affdir, out = sys.argv[1:4]
rows = []
r = None
for line in open(csv).read().splitlines()[2:]:
    f = line.split(";")
    if not f[1].strip():
        continue
    if f[0].strip():
        r = int(f[0])
    c = int(f[1])
    v = tuple(int(x) for x in f[2:10])
    rows.append((r, c, v))
print("entries", len(rows), "rows", max(e[0] for e in rows) + 1, "cols", max(e[1] for e in rows) + 1)
LS = [[a * 2 ** j for j in range(9) if a * 2 ** j <= 384] for a in (2, 3, 5, 7, 9, 11, 13, 15)]
# cross-check every lifted matrix AFF3CT ships
n_ok = 0
for fn in sorted(glob.glob(os.path.join(affdir, "NR_1_*_*.qc"))):
    m = re.match(r"NR_1_(\d)_(\d+)\.qc", os.path.basename(fn))
    ils, Z = int(m.group(1)), int(m.group(2))
    assert Z in LS[ils], (ils, Z)
    nums = open(fn).read().split()
    nc, nr, z2 = int(nums[0]), int(nums[1]), int(nums[2])
    assert (nc, nr, z2) == (68, 46, Z)
    H = [[int(x) for x in nums[3 + i * nc: 3 + (i + 1) * nc]] for i in range(nr)]
    mine = [[-1] * 68 for _ in range(46)]
    for (rr, cc, v) in rows:
        mine[rr][cc] = v[ils] % Z
    assert H == mine, fn
    n_ok += 1
print("AFF3CT matrices identical:", n_ok)
with open(out, "w") as fo:
    fo.write('"""5G NR LDPC base graph 1 (3GPP TS 38.212 Table 5.3.2-2): (row, column, V[iLS=0..7]).\n\n'
             'Shift for lifting size Z in set iLS = V mod Z.  Generated by tools/gen_bg1 from the table in\n'
             'NVIDIA Sionna (5G_bg1.csv) and verified entry by entry against the lifted matrices of AFF3CT\n'
             f'({n_ok} lifting sizes).  46 rows x 68 columns, {len(rows)} non-zero entries.\n"""\n\n')
    fo.write("BG1 = (\n")
    for (rr, cc, v) in rows:
        fo.write(f"    ({rr}, {cc}, {v}),\n")
    fo.write(")\n")
print("wrote", out)
